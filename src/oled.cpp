bool oled_init(void)
{
    bus_initialized = true;
    oled_ok = true;
    oled_error = 0;

    // Initialize PB6 (SCL) and PB7 (SDA) as Output Open-Drain for software I2C
    __HAL_RCC_GPIOB_CLK_ENABLE();
    GPIO_InitTypeDef gpio = {0};
    gpio.Pin = GPIO_PIN_6 | GPIO_PIN_7;
    gpio.Mode = GPIO_MODE_OUTPUT_OD;
    gpio.Pull = GPIO_PULLUP;
    gpio.Speed = GPIO_SPEED_FREQ_HIGH;
    HAL_GPIO_Init(GPIOB, &gpio);

    i2c_start();
    bool ack = i2c_write_byte((uint8_t)OLED_ADDR);
    i2c_stop();
    if (!ack) {
        oled_ok = false;
        oled_error = 1;
        return false;
    }

    cmd(0xAE); /* display off */
    cmd(0x20); /* memory mode */
    cmd(0x00); /* horizontal addressing */
    cmd(0xC8); /* COM scan inc */
    cmd(0xA1); /* segment remap */
    cmd(0x8D); /* charge pump */
    cmd(0x14); /* enable */
    cmd(0xAF); /* display on */

    memset(fb, 0, sizeof(fb));
    flush();

    return oled_ok;
}

uint8_t oled_error_stage(void)
{
    return oled_error;
}

void oled_clear(void)
{
    memset(fb, 0, sizeof(fb));
    flush();
}

void oled_show_text(uint8_t col, uint8_t page, const char *text)
{
    if (!bus_initialized) return;

    while (*text && col < FB_W - FONT_W) {
        char c = *text++;
        if (c >= 32 && c <= 126) {
            const uint8_t *glyph = font5x8[c - 32];
            for (uint8_t i = 0; i < FONT_W; i++) {
                fb[page][col + i] = glyph[i];
            }
        }
        col += FONT_W + 1;
    }
    flush();
}