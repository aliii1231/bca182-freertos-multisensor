void oled_bus_init(void)
{
    if (bus_initialized) return;

    __HAL_RCC_GPIOB_CLK_ENABLE();

    GPIO_InitTypeDef g = {0};
    g.Pin = GPIO_PIN_6 | GPIO_PIN_7;     /* B6=SCL, B7=SDA */
    g.Mode = GPIO_MODE_OUTPUT_OD;        /* Direct GPIO I2C, matching reference */
    g.Pull = GPIO_PULLUP;
    g.Speed = GPIO_SPEED_FREQ_HIGH;
    HAL_GPIO_Init(GPIOB, &g);

    sda_high();
    scl_high();
    bus_initialized = true;
}

bool oled_init(void)
{
    oled_bus_init();

    /* SSD1306 init sequence matched to the working RENE reference. */
    cmd(0xAE);
    cmd(0x20); cmd(0x00);
    cmd(0xB0);
    cmd(0xC8);
    cmd(0x00); cmd(0x10);
    cmd(0x40);
    cmd(0x81); cmd(0xFF);
    cmd(0xA1);
    cmd(0xA6);
    cmd(0xA8); cmd(0x3F);
    cmd(0xA4);
    cmd(0xD3); cmd(0x00);
    cmd(0xD5); cmd(0xF0);
    cmd(0xD9); cmd(0x22);
    cmd(0xDA); cmd(0x12);
    cmd(0xDB); cmd(0x20);
    cmd(0x8D); cmd(0x14);
    cmd(0xAF);
    return oled_ok;
}

uint8_t oled_error_stage(void)
{
    return oled_error;
}

void oled_clear(void)
{
    memset(fb, 0, sizeof fb);
    flush();
}

/* page 0..7 (8 rows each), col 0..122 */
void oled_show_text(uint8_t col, uint8_t page, const char *text)
{
    if (page > 7) page = 7;
    uint8_t x = col;
    while (*text && x + FONT_W < FB_W) {
        char c = *text++;
        if (c < ' ' || c > '}') c = ' ';
        const uint8_t *glyph = font5x8[c - ' '];
        for (int i = 0; i < FONT_W; i++) {
            fb[page][x] = glyph[i];
            x++;
        }
        fb[page][x] = 0x00;              /* 1-px inter-char gap */
        x++;
    }
    flush();
}